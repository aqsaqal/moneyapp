"""Generate utils/db/demoText.ts from assets/store/generic/listings/demo-<lang>.json.

  python3 scripts/demo-text.py

The Demo profile's sample labels (accounts, bills, notes) in the twelve store languages.
"""
import json, os
SRC = 'assets/store/generic/listings'
LOCALES = {'es': 'es-ES', 'pt': 'pt-BR', 'fr': 'fr-FR', 'de': 'de-DE', 'tr': 'tr-TR', 'id': 'id-ID', 'ru': 'ru-RU',
           'kk': 'kk-KZ', 'ja': 'ja-JP', 'ko': 'ko-KR', 'zh': 'zh-CN'}
out = ['// Generated by scripts/demo-text.py from assets/store/generic/listings/demo-<lang>.json. Do not edit by hand.',
       '', 'export const DEMO_TEXT: Record<string, Record<string, string>> = {']
for code, locale in LOCALES.items():
    path = f'{SRC}/demo-{code}.json'
    if not os.path.exists(path):
        continue
    d = json.load(open(path))
    out.append(f"  '{locale}': {json.dumps(d, ensure_ascii=False)},")
out += ['};', '']
open('utils/db/demoText.ts', 'w').write('\n'.join(out))
print('wrote utils/db/demoText.ts')
